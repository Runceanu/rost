#!/usr/bin/env node
/**
 * Writes docs/components/<id>.md for every contract and docs/README.md, the
 * catalogue. Markdown so it reads in the repo and in an agent's context alike;
 * rost.build (web/) renders the same model for browsing.
 */
import { mkdirSync, writeFileSync, readdirSync, rmSync, readFileSync } from 'node:fs'
import { loadKit, loadTokens, KINDS, APP_LABEL, title, sourceLink, guidanceMarkdown, COVERAGE, classify } from './lib/kit.mjs'

const kit = loadKit()
const out = new URL('../docs/components/', import.meta.url)
mkdirSync(out, { recursive: true })
for (const f of readdirSync(out)) if (f.endsWith('.md')) rmSync(new URL(f, out))

const GENERATED = (id) =>
  `<!-- Generated by bin/build-docs.mjs. Edit contracts/${id}.contract.yaml, then run npm run docs. -->`
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')
const apps = (e) => e.implementations.map((i) => APP_LABEL[i.app] ?? i.app).join(', ')

function page(e) {
  const { c, guidance: g } = e
  const src = sourceLink(c)
  const lines = [GENERATED(e.id), '', `# ${title(e)}`, '']
  if (c.summary) lines.push(`> ${c.summary}`, '')

  lines.push(
    '| | |', '|---|---|',
    `| Kind | ${e.kind} |`,
    `| Contract | \`${c.status}\` · [${e.file}](../../contracts/${e.file}) |`,
    `| Guidance | ${g ? `\`${g.status}\`` : '**missing**'} |`,
    `| Source | ${src.href ? `[${src.label}](${src.href})` : `\`${src.label}\``}${c.source.extractedAt ? ` · read ${c.source.extractedAt}` : ''}${c.source.frozenAt ? ` · frozen ${c.source.frozenAt}` : ''} |`,
    `| Implemented in | ${e.implementations.length ? e.implementations.map((i) => `${APP_LABEL[i.app] ?? i.app} (\`${i.component}\`${i.root ? `, \`${i.root}\`` : ''})`).join('<br>') : 'nowhere yet'} |`,
    '',
  )

  // Problems first: a reader building on this should see them before the spec.
  const problems = []
  if (e.unresolved.length) problems.push(`These tokens aren't in \`tokens/tokens.css\` yet: ${e.unresolved.map((t) => `\`${t}\``).join(', ')}.`)
  if (c.pending?.reason) problems.push(`Still to read: ${c.pending.reason}`)
  if (!g) problems.push(`No guidance yet. It needs a \`guidance\` block (there's one to copy in \`schema/template.contract.yaml\`).`)
  if (problems.length) lines.push('## Not right yet', '', ...problems.map((p) => `- ${p}`), '')

  const props = Object.entries(c.props ?? {})
  if (props.length) {
    lines.push('## Props', '', '| Prop | Type | Values | Default |', '|---|---|---|---|')
    for (const [k, v] of props) lines.push(`| \`${k}\` | ${v.type} | ${(v.values ?? []).map((x) => `\`${x}\``).join(' ')} | ${v.default !== undefined ? `\`${v.default}\`` : ''} |`)
    lines.push('')
  }
  if (c.states?.length) lines.push('## States', '', c.states.map((s) => `\`${s}\``).join(' · '), '')

  const parts = Object.entries(c.elements ?? {})
  if (parts.length) {
    lines.push('## Anatomy', '')
    for (const [part, el] of parts) lines.push(`- \`${part}\`${el.optional ? ' (optional)' : ''}${el.notes ? `: ${cell(el.notes)}` : ''}`)
    lines.push('')
  }

  if (g) lines.push(guidanceMarkdown(g), '')

  if (e.deviations.length) {
    lines.push('## Where code differs on purpose', '', '| App | What | Why | Taken to design |', '|---|---|---|---|')
    for (const d of e.deviations) lines.push(`| ${APP_LABEL[d.app] ?? d.app ?? 'all'} | ${cell(d.what)} | ${cell(d.why)} | ${d.raisedWithDesign ? 'yes' : 'not yet'} |`)
    lines.push('')
  }

  if (e.tokens.size) {
    lines.push('## Tokens', '', 'Every token this component uses, across all its variants.', '', '| Token | Resolves to |', '|---|---|')
    for (const [t, v] of [...e.tokens].sort()) lines.push(`| \`${t}\`${e.unresolved.includes(t) ? ' ⚠︎' : ''} | \`${cell(v)}\` |`)
    lines.push('')
  }

  const suggested = [...new Map(e.values.filter((x) => x.v.suggest).map((x) => [`${x.part}.${x.prop}=${x.v.suggest}`, x])).values()]
  if (suggested.length) {
    lines.push('## Tokens that should be there', '', 'A token I want here that `tokens.css` doesn\'t have yet. Creating it is the next step.', '', '| Part | Property | Value | Suggest | |', '|---|---|---|---|---|')
    for (const x of suggested) lines.push(`| \`${x.part}\` | \`${x.prop}\` | \`${cell(x.v.value)}\` | \`${x.v.suggest}\` | ${e.resolves(x.v.suggest) ? 'exists' : '**new token**'} |`)
    lines.push('')
  }
  const reasoned = e.values.filter((x) => x.v.untokenised)
  if (reasoned.length) {
    lines.push('## No token, on purpose', '', '| Part | Property | Value | Why |', '|---|---|---|---|')
    for (const x of reasoned) lines.push(`| \`${x.part}\` | \`${x.prop}\` | \`${cell(x.v.value)}\` | ${cell(x.v.untokenised)} |`)
    lines.push('')
  }

  lines.push(`See it live, with every value of every variant: [rost.build/components/${e.id}](https://rost.build/components/${e.id}/)`, '')
  return lines.join('\n')
}

for (const e of kit) writeFileSync(new URL(`${e.id}.md`, out), page(e))

// ─── Catalogue ───────────────────────────────────────────────────────────────
const by = (k) => kit.filter((e) => e.kind === k)
const catalogue = KINDS.filter(([k]) => by(k).length).map(([k, label]) => [
  `### ${label}`, '',
  '| | Summary | Contract | Guidance | Used in |', '|---|---|---|---|---|',
  ...by(k).map((e) => `| [${title(e)}](components/${e.id}.md) | ${cell(e.c.summary ?? '')} | \`${e.c.status}\` | ${e.guidance ? `\`${e.guidance.status}\`` : '·'} | ${apps(e) || '·'} |`),
  '',
].join('\n')).join('\n')

const health = [
  ['Tokens missing from tokens.css', kit.filter((e) => e.unresolved.length).map((e) => `[${title(e)}](components/${e.id}.md): ${e.unresolved.map((t) => `\`${t}\``).join(', ')}`)],
  ['Still open from Figma', kit.filter((e) => e.c.pending).map((e) => `[${title(e)}](components/${e.id}.md)`)],
  ['No guidance yet', by('component').filter((e) => !e.guidance).map((e) => `[${title(e)}](components/${e.id}.md)`)],
  ['Differences nobody has taken to design yet', kit.flatMap((e) => e.deviations.filter((d) => !d.raisedWithDesign).map((d) => `[${title(e)}](components/${e.id}.md)${d.app ? ` in ${APP_LABEL[d.app] ?? d.app}` : ''}: ${cell(d.what).split('. ')[0].replace(/\.$/, '')}`))],
].filter(([, items]) => items.length)

const counts = {
  total: kit.length,
  stable: kit.filter((e) => e.c.status === 'stable').length,
  agreed: kit.filter((e) => e.guidance?.status === 'agreed').length,
  guided: kit.filter((e) => e.guidance).length,
}

writeFileSync(new URL('../docs/README.md', import.meta.url), `${GENERATED('*')}

# Rost: documentation

Rost started as a design system for my own needs and grew into a product of its own. Today it serves products across different industries. Start here.

| Read | For |
|---|---|
| [How a contract works](CONTRACT.md) | What's in one, how it grows up, when it's done, how to add one |
| [Components](#catalogue) | A page per component: how to use it, props, parts, tokens, where code differs |
| [rost.build](https://rost.build) | Every component, live where it's built, with every value of every variant |
| [Token coverage](TOKENS.md) | Why each value has a token or doesn't |
| [Roadmap](ROADMAP.md) | What I'm doing next |

**${counts.total}** contracts, **${counts.stable}** stable. **${counts.guided}** have guidance, and I've signed off **${counts.agreed}** of those.

## Catalogue

${catalogue}
## Health

What needs attention. It's built from the contracts, so it's only as fresh as the last \`npm run docs\`.

${health.map(([h, items]) => `### ${h}\n\n${items.map((i) => `- ${i}`).join('\n')}\n`).join('\n') || 'Nothing needs attention right now.\n'}`)

// ─── Token coverage ──────────────────────────────────────────────────────────
const total = Object.fromEntries(COVERAGE.map(([k]) => [k, kit.reduce((n, e) => n + e.coverage[k], 0)]))
const all = Object.values(total).reduce((a, b) => a + b, 0)
const pct = (n) => `${Math.round((n / all) * 100)}%`
const suggestions = new Map()
for (const e of kit) for (const x of e.values) if (x.v.suggest) {
  const k = `${x.v.suggest}|${x.v.value}`
  const row = suggestions.get(k) ?? { token: x.v.suggest, value: x.v.value, exists: e.resolves(x.v.suggest), where: new Set(), n: 0 }
  row.where.add(`[${title(e)}](components/${e.id}.md) \`${x.part}.${x.prop}\``); row.n++
  suggestions.set(k, row)
}
const figmaVars = JSON.parse(readFileSync(new URL('../registry/figma-variables.json', import.meta.url), 'utf8')).paths
const { vars } = loadTokens()
const unexported = figmaVars.filter((p) => !vars.has('--' + p.replace(/[/ ]/g, '-')))
const families = {}
for (const p of unexported) { const f = p.split('/').slice(0, p.startsWith('spacing/base') ? 1 : 2).join('/'); families[f] = (families[f] ?? 0) + 1 }

writeFileSync(new URL('../docs/TOKENS.md', import.meta.url), `${GENERATED('*')}

# Token coverage

Every value in every contract, sorted by why it has a token or doesn't. \`npm run docs\` refreshes it.

| | Values | Share | Meaning |
|---|---|---|---|
${COVERAGE.map(([k, label]) => `| ${label} | ${total[k]} | ${pct(total[k])} | ${{
  token: 'Uses a token, and the check tests it.',
  suggested: 'A token I want that doesn\'t exist yet. The freeze turned every other suggestion into a token.',
  layout: 'How Figma builds the layer (position, inset, which sides get a stroke). Nothing to tokenise.',
  sample: 'A root size that is just the Figma frame. Written down, not checked.',
  reasoned: 'Plain on purpose, and the contract says why.',
  gap: 'No token and no reason. Each one needs a decision from me.',
}[k]} |`).join('\n')}

## By contract

| | ${COVERAGE.map(([, l]) => l).join(' | ')} |
|---|${COVERAGE.map(() => '---:').join('|')}|
${kit.map((e) => `| [${title(e)}](components/${e.id}.md) | ${COVERAGE.map(([k]) => e.coverage[k] || '·').join(' | ')} |`).join('\n')}

## Tokens that should be there

${suggestions.size ? `Tokens I want that \`tokens.css\` doesn't have yet. Anything marked **new** needs creating first.

| Suggest | Value | Exists | Uses | Where |
|---|---|---|---:|---|
${[...suggestions.values()].sort((a, b) => b.n - a.n).map((r) => `| \`${r.token}\` | \`${r.value}\` | ${r.exists ? 'yes' : '**new**'} | ${r.n} | ${[...r.where].slice(0, 4).join(', ')}${r.where.size > 4 ? ` +${r.where.size - 4}` : ''} |`).join('\n')}` : 'None. The freeze on 2026-10-20 turned all 122 suggestions into tokens.'}

## No token, on purpose

${kit.flatMap((e) => e.values.filter((x) => x.v.untokenised).map((x) => `- [${title(e)}](components/${e.id}.md) \`${x.part}.${x.prop}\` = \`${x.v.value}\`: ${x.v.untokenised}`)).join('\n') || 'None.'}

## Open gaps

${kit.flatMap((e) => e.values.filter((x) => classify(x.prop, x.v) === 'gap').map((x) => `- [${title(e)}](components/${e.id}.md) \`${x.part}.${x.prop}\` = \`${x.v.value}\``)).join('\n') || 'None. Every value has a token, a suggestion, or a reason.'}

## Figma variables missing from tokens.css

The Figma file has **${figmaVars.length}** variables (\`registry/figma-variables.json\`) and \`tokens/tokens.css\` has **${figmaVars.length - unexported.length}** of them. No contract needs the other ${unexported.length} today, but new components will, the way Chip needed \`opacity/strong\`.

| Family | Missing |
|---|---:|
${Object.entries(families).sort((a, b) => b[1] - a[1]).map(([f, n]) => `| \`${f}\` | ${n} |`).join('\n')}
`)

console.log(`docs: ${kit.length} component pages + README (${counts.guided} with guidance)`)
