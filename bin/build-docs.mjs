#!/usr/bin/env node
/**
 * Writes docs/components/<id>.md for every contract and docs/README.md, the
 * catalogue. Markdown so it reads in the repo and in an agent's context alike;
 * rost.build (web/) renders the same model for browsing.
 */
import { mkdirSync, writeFileSync, readdirSync, rmSync, readFileSync } from 'node:fs'
import { loadKit, loadTokens, KINDS, APP_LABEL, title, sourceLink, guidanceMarkdown, COVERAGE, classify, plainGroups } from './lib/kit.mjs'

const kit = loadKit()
const out = new URL('../docs/components/', import.meta.url)
mkdirSync(out, { recursive: true })
for (const f of readdirSync(out)) if (f.endsWith('.md')) rmSync(new URL(f, out))

const GENERATED = (id) =>
  `<!-- Generated by bin/build-docs.mjs. Edit contracts/${id}.contract.yaml, then run npm run docs. -->`
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')
const apps = (e) => e.implementations.map((i) => APP_LABEL[i.app] ?? i.app).join(', ')

function page(e) {
  const { c, guidance: g } = e
  const src = sourceLink(c)
  const lines = [GENERATED(e.id), '', `# ${title(e)}`, '']
  if (c.summary) lines.push(`> ${c.summary}`, '')

  lines.push(
    '| | |', '|---|---|',
    `| Kind | ${e.kind} |`,
    `| Contract | \`${c.status}\` · [${e.file}](../../contracts/${e.file}) |`,
    `| Guidance | ${g ? `\`${g.status}\`` : '**missing**'} |`,
    `| Source | ${src.href ? `[${src.label}](${src.href})` : `\`${src.label}\``}${c.source.extractedAt ? ` · read ${c.source.extractedAt}` : ''}${c.source.frozenAt ? ` · frozen ${c.source.frozenAt}` : ''} |`,
    `| Implemented in | ${e.implementations.length ? e.implementations.map((i) => `${APP_LABEL[i.app] ?? i.app} (\`${i.component}\`${i.root ? `, \`${i.root}\`` : ''})`).join('<br>') : 'nowhere yet'} |`,
    '',
  )

  // Problems first: a reader building on this should see them before the spec.
  const problems = []
  if (e.unresolved.length) problems.push(`These tokens aren't in \`tokens/tokens.css\` yet: ${e.unresolved.map((t) => `\`${t}\``).join(', ')}.`)
  if (c.pending?.reason) problems.push(`Still to read: ${c.pending.reason}`)
  if (!g) problems.push(`No guidance yet. It needs a \`guidance\` block (there's one to copy in \`schema/template.contract.yaml\`).`)
  if (problems.length) lines.push('## Not right yet', '', ...problems.map((p) => `- ${p}`), '')

  const props = Object.entries(c.props ?? {})
  if (props.length) {
    lines.push('## Props', '', '| Prop | Type | Values | Default |', '|---|---|---|---|')
    for (const [k, v] of props) lines.push(`| \`${k}\` | ${v.type} | ${(v.values ?? []).map((x) => `\`${x}\``).join(' ')} | ${v.default !== undefined ? `\`${v.default}\`` : ''} |`)
    lines.push('')
  }
  if (c.states?.length) lines.push('## States', '', c.states.map((s) => `\`${s}\``).join(' · '), '')

  const parts = Object.entries(c.elements ?? {})
  if (parts.length) {
    lines.push('## Anatomy', '')
    for (const [part, el] of parts) lines.push(`- \`${part}\`${el.optional ? ' (optional)' : ''}${el.notes ? `: ${cell(el.notes)}` : ''}`)
    lines.push('')
  }

  if (g) lines.push(guidanceMarkdown(g), '')

  if (e.deviations.length) {
    lines.push('## Where code differs on purpose', '', '| App | What | Why | Taken to design |', '|---|---|---|---|')
    for (const d of e.deviations) lines.push(`| ${APP_LABEL[d.app] ?? d.app ?? 'all'} | ${cell(d.what)} | ${cell(d.why)} | ${d.raisedWithDesign ? 'yes' : 'not yet'} |`)
    lines.push('')
  }

  if (e.tokens.size) {
    lines.push('## Tokens', '', 'Every token this component uses, across all its variants.', '', '| Token | Resolves to |', '|---|---|')
    for (const [t, v] of [...e.tokens].sort()) lines.push(`| \`${t}\`${e.unresolved.includes(t) ? ' ⚠︎' : ''} | \`${cell(v)}\` |`)
    lines.push('')
  }

  const suggested = [...new Map(e.values.filter((x) => x.v.suggest).map((x) => [`${x.part}.${x.prop}=${x.v.suggest}`, x])).values()]
  if (suggested.length) {
    lines.push('## Tokens that should be there', '', 'A token I want here that `tokens.css` doesn\'t have yet. Creating it is the next step.', '', '| Part | Property | Value | Suggest | |', '|---|---|---|---|---|')
    for (const x of suggested) lines.push(`| \`${x.part}\` | \`${x.prop}\` | \`${cell(x.v.value)}\` | \`${x.v.suggest}\` | ${e.resolves(x.v.suggest) ? 'exists' : '**new token**'} |`)
    lines.push('')
  }
  const reasoned = e.values.filter((x) => x.v.untokenised)
  if (reasoned.length) {
    lines.push('## No token, on purpose', '', '| Part | Property | Value | Why |', '|---|---|---|---|')
    for (const x of reasoned) lines.push(`| \`${x.part}\` | \`${x.prop}\` | \`${cell(x.v.value)}\` | ${cell(x.v.untokenised)} |`)
    lines.push('')
  }

  lines.push(`See it live, with every value of every variant: [rost.build/components/${e.id}](https://rost.build/components/${e.id}/)`, '')
  return lines.join('\n')
}

for (const e of kit) writeFileSync(new URL(`${e.id}.md`, out), page(e))

// ─── Catalogue ───────────────────────────────────────────────────────────────
const by = (k) => kit.filter((e) => e.kind === k)
const catalogue = KINDS.filter(([k]) => by(k).length).map(([k, label]) => [
  `### ${label}`, '',
  '| | Summary | Contract | Guidance | Used in |', '|---|---|---|---|---|',
  ...by(k).map((e) => `| [${title(e)}](components/${e.id}.md) | ${cell(e.c.summary ?? '')} | \`${e.c.status}\` | ${e.guidance ? `\`${e.guidance.status}\`` : '·'} | ${apps(e) || '·'} |`),
  '',
].join('\n')).join('\n')

const health = [
  ['Tokens missing from tokens.css', kit.filter((e) => e.unresolved.length).map((e) => `[${title(e)}](components/${e.id}.md): ${e.unresolved.map((t) => `\`${t}\``).join(', ')}`)],
  ['Still open from Figma', kit.filter((e) => e.c.pending).map((e) => `[${title(e)}](components/${e.id}.md)`)],
  ['No guidance yet', by('component').filter((e) => !e.guidance).map((e) => `[${title(e)}](components/${e.id}.md)`)],
  ['Differences nobody has taken to design yet', kit.flatMap((e) => e.deviations.filter((d) => !d.raisedWithDesign).map((d) => `[${title(e)}](components/${e.id}.md)${d.app ? ` in the ${(APP_LABEL[d.app] ?? d.app).toLowerCase()}` : ''}: ${cell(d.what).split('. ')[0].replace(/\.$/, '')}`))],
].filter(([, items]) => items.length)

const counts = {
  total: kit.length,
  stable: kit.filter((e) => e.c.status === 'stable').length,
  agreed: kit.filter((e) => e.guidance?.status === 'agreed').length,
  guided: kit.filter((e) => e.guidance).length,
}

