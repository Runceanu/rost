#!/usr/bin/env node
/**
 * Turns the illustration SVGs into inline markup the theme can colour.
 *
 * Every drawing is made of three colours: Figma's dark grey, its mid grey and
 * its green. Each becomes a class, and illustration.css (from the contract)
 * gives each class its token, `illustration/shade`, `illustration/form` and
 * `illustration/accent`, so the drawings change with the theme. A drawing in a
 * fourth colour stops the build: it needs a token first.
 *
 *   node bin/build-illustrations.mjs           write src/components/illustration/drawings.ts
 *   node bin/build-illustrations.mjs --check   exit 1 if it's out of date
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const dir = fileURLToPath(new URL('../src/components/illustration/', import.meta.url))
const check = process.argv.includes('--check')
const PART = { '#232423': 'shade', '#454545': 'form', '#37d273': 'accent' }

const drawings = {}
for (const file of readdirSync(`${dir}svg`).filter((f) => f.endsWith('.svg')).sort()) {
  const name = file.replace(/\.svg$/, '')
  let svg = readFileSync(`${dir}svg/${file}`, 'utf8').trim()
  svg = svg
    // The <svg> takes its size from the component; ids would clash with other drawings on the page.
    .replace(/<svg[^>]*>/, (tag) => tag.replace(/\s(preserveAspectRatio|overflow|style|width|height|xmlns)="[^"]*"/g, ''))
    .replace(/\sid="[^"]*"/g, '')
    .replace(/<svg/, '<svg class="rost-illustration__drawing" xmlns="http://www.w3.org/2000/svg"')
    .replace(/fill="(#[0-9a-fA-F]{6})"/g, (m, hex) => {
      const part = PART[hex.toLowerCase()]
      if (!part) throw new Error(`${file}: ${hex} has no illustration token`)
      return `class="rost-illustration__${part}"`
    })
    .replace(/\n\s*/g, '')
  drawings[name] = svg
}

const out = `// Generated by bin/build-illustrations.mjs from svg/*.svg. Don't edit by hand.
// Each drawing's colours are classes; illustration.css gives them the illustration tokens.
export const DRAWINGS: Record<string, string> = {
${Object.entries(drawings).map(([k, v]) => `  '${k}': ${JSON.stringify(v)},`).join('\n')}
}
`
const target = `${dir}drawings.ts`
if (check) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== out) { console.error('drawings.ts is out of date: node bin/build-illustrations.mjs'); process.exit(1) }
  console.log('illustrations: up to date')
} else {
  writeFileSync(target, out)
  console.log(`illustrations: ${Object.keys(drawings).length} drawings`)
}
